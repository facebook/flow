if command -v cmd.exe > /dev/null 2>&1; then
  rm -rf \
    extensionless_link \
    file_link.js \
    ignored_alias \
    node_modules/symlink_lib \
    node_modules/symlink_lib_outside_root \
    outer_link \
    ../nested_outer_target/inner_link \
    ../unwatched/dir_link
  cmd.exe /D /S /C 'mklink extensionless_link util.js' > /dev/null
  cmd.exe /D /S /C 'mklink file_link.js util.js' > /dev/null
  cmd.exe /D /S /C 'mklink /D ignored_alias ..\nested_inner_target' > /dev/null
  cmd.exe /D /S /C 'mklink /D node_modules\symlink_lib ..\symlink_lib' > /dev/null
  cmd.exe /D /S /C 'mklink /D node_modules\symlink_lib_outside_root ..\..\symlink_lib_outside_root' > /dev/null
  cmd.exe /D /S /C 'mklink /D outer_link ..\nested_outer_target' > /dev/null
  cmd.exe /D /S /C 'mklink /D ..\nested_outer_target\inner_link ..\nested_inner_target' > /dev/null
  cmd.exe /D /S /C 'mklink /D ..\unwatched\dir_link ..\root\dir' > /dev/null
fi

printf "Scratch init:\n"
assert_errors "$FLOW" status .

printf "\nRecheck after scratch init:\n"
printf "\n// recheck after scratch init\n" >> foo.js
assert_ok "$FLOW" force-recheck --no-auto-start foo.js
assert_errors "$FLOW" status --no-auto-start .

assert_ok "$FLOW" save-state --root . --out .flow.saved_state > /dev/null
assert_ok "$FLOW" stop .
: > .flow.saved_state_file_changes

printf "\nSaved-state init:\n"
start_flow . --saved-state-fetcher local --saved-state-no-fallback
assert_errors "$FLOW" status --no-auto-start .

printf "\nRecheck after saved-state init:\n"
printf "\n// recheck after saved-state init\n" >> foo.js
assert_ok "$FLOW" force-recheck --no-auto-start foo.js
assert_errors "$FLOW" status --no-auto-start .

assert_ok "$FLOW" stop .
